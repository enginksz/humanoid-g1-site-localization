// Equivalent of Preprocess for a generic time-stamped cloud: keep every
// point_filter_num-th point beyond the blind radius; curvature = time [ms].
static PointCloudXYZI::Ptr toCloud(const std::vector<RawPoint>& pts, int point_filter_num, double blind) {
    PointCloudXYZI::Ptr c(new PointCloudXYZI());
    c->reserve(pts.size() / point_filter_num + 1);
    for (size_t i = 0; i < pts.size(); i += point_filter_num) {
        const auto& p = pts[i];
        if (double(p.x) * p.x + double(p.y) * p.y + double(p.z) * p.z < blind * blind) continue;
        PointType q;
        q.x = p.x; q.y = p.y; q.z = p.z;
        q.intensity = 0.f;
        q.normal_x = q.normal_y = q.normal_z = 0.f;
        q.curvature = p.t_off * 1000.f;
        c->push_back(q);
    }
    std::sort(c->points.begin(), c->points.end(), [](const PointType& a, const PointType& b) { return a.curvature < b.curvature; });
    return c;
}

int main(int argc, char** argv)
{
    if (argc < 4) { std::cerr << "usage: fast_lio_offline config.yaml seq_dir out_dir [key=value ...]\n"; return 1; }
    const std::string seq_dir = argv[2], out_dir = argv[3];
    ros::NodeHandle nh(argv[1]);
    for (int i = 4; i < argc; ++i) {
        std::string kv = argv[i]; auto eq = kv.find('=');
        if (eq != std::string::npos) nh.set(kv.substr(0, eq), kv.substr(eq + 1));
    }
    int point_filter_num; double blind;
    // ---- parameters: same keys and defaults as laserMapping.cpp main()
    nh.param<int>("max_iteration",NUM_MAX_ITERATIONS,4);
    nh.param<double>("common/time_offset_lidar_to_imu", time_diff_lidar_to_imu, 0.0);
    nh.param<double>("filter_size_surf",filter_size_surf_min,0.5);
    nh.param<double>("filter_size_map",filter_size_map_min,0.5);
    nh.param<double>("cube_side_length",cube_len,200);
    nh.param<float>("mapping/det_range",DET_RANGE,300.f);
    nh.param<double>("mapping/fov_degree",fov_deg,180);
    nh.param<double>("mapping/gyr_cov",gyr_cov,0.1);
    nh.param<double>("mapping/acc_cov",acc_cov,0.1);
    nh.param<double>("mapping/b_gyr_cov",b_gyr_cov,0.0001);
    nh.param<double>("mapping/b_acc_cov",b_acc_cov,0.0001);
    nh.param<double>("preprocess/blind", blind, 0.01);
    nh.param<int>("point_filter_num", point_filter_num, 2);
    nh.param<bool>("mapping/extrinsic_est_en", extrinsic_est_en, true);
    nh.param<vector<double>>("mapping/extrinsic_T", extrinT, vector<double>());
    nh.param<vector<double>>("mapping/extrinsic_R", extrinR, vector<double>());
    lidar_type = 2;  // VELO16-like generic cloud (not MARSIM, not AVIA)

    FOV_DEG = (fov_deg + 10.0) > 179.9 ? 179.9 : (fov_deg + 10.0);
    HALF_FOV_COS = cos((FOV_DEG) * 0.5 * PI_M / 180.0);
    _featsArray.reset(new PointCloudXYZI());
    memset(point_selected_surf, true, sizeof(point_selected_surf));
    memset(res_last, -1000.0f, sizeof(res_last));
    downSizeFilterSurf.setLeafSize(filter_size_surf_min, filter_size_surf_min, filter_size_surf_min);
    downSizeFilterMap.setLeafSize(filter_size_map_min, filter_size_map_min, filter_size_map_min);
    Lidar_T_wrt_IMU<<VEC_FROM_ARRAY(extrinT);
    Lidar_R_wrt_IMU<<MAT_FROM_ARRAY(extrinR);
    p_imu->set_extrinsic(Lidar_T_wrt_IMU, Lidar_R_wrt_IMU);
    p_imu->set_gyr_cov(V3D(gyr_cov, gyr_cov, gyr_cov));
    p_imu->set_acc_cov(V3D(acc_cov, acc_cov, acc_cov));
    p_imu->set_gyr_bias_cov(V3D(b_gyr_cov, b_gyr_cov, b_gyr_cov));
    p_imu->set_acc_bias_cov(V3D(b_acc_cov, b_acc_cov, b_acc_cov));
    p_imu->lidar_type = lidar_type;
    double epsi[23] = {0.001};
    fill(epsi, epsi+23, 0.001);
    kf.init_dyn_share(get_f, df_dx, df_dw, h_share_model, NUM_MAX_ITERATIONS, epsi);

    std::filesystem::create_directories(out_dir);
    std::ofstream fpose(out_dir + "/poses_tum.txt"), fstat(out_dir + "/scan_stats.csv");
    fstat << "t,proc_ms,n_down,n_effective\n";

    // ---- read inputs
    std::vector<ImuRec> imu;
    { FILE* f = fopen((seq_dir + "/imu.bin").c_str(), "rb"); ImuRec r;
      while (f && fread(&r, sizeof r, 1, f) == 1) imu.push_back(r); if (f) fclose(f); }
    FILE* lf = fopen((seq_dir + "/lidar.bin").c_str(), "rb");
    if (!lf || imu.empty()) { std::cerr << "missing input\n"; return 1; }

    size_t imu_i = 0, n_scans = 0;
    double t_beg; uint32_t n; std::vector<RawPoint> pts;
    auto wall0 = std::chrono::steady_clock::now();
    while (fread(&t_beg, sizeof(double), 1, lf) == 1 && fread(&n, sizeof(n), 1, lf) == 1) {
        pts.resize(n);
        if (fread(pts.data(), sizeof(RawPoint), n, lf) != n) break;
        const double t_end = t_beg + (n ? pts.back().t_off : 0.0);
        while (imu_i < imu.size() && imu[imu_i].t <= t_end + 0.02) {
            sensor_msgs::Imu::Ptr m(new sensor_msgs::Imu());
            const auto& r = imu[imu_i++];
            m->header.stamp = ros::Time(r.t);
            m->angular_velocity = {r.wx, r.wy, r.wz};
            m->linear_acceleration = {r.ax, r.ay, r.az};
            imu_cbk(m);
        }
        // standard_pcl_cbk equivalent
        lidar_buffer.push_back(toCloud(pts, point_filter_num, blind));
        time_buffer.push_back(t_beg);
        last_timestamp_lidar = t_beg;
        ++n_scans;

        // ===== main loop body, as in laserMapping.cpp main() (publishers removed)
        while (sync_packages(Measures))
        {
            if (flg_first_scan)
            {
                first_lidar_time = Measures.lidar_beg_time;
                p_imu->first_lidar_time = first_lidar_time;
                flg_first_scan = false;
                continue;
            }
            double t0 = omp_get_wtime();
            match_time = 0; kdtree_search_time = 0.0; solve_time = 0; solve_const_H_time = 0;

            p_imu->Process(Measures, kf, feats_undistort);
            state_point = kf.get_x();
            pos_lid = state_point.pos + state_point.rot * state_point.offset_T_L_I;
            if (feats_undistort->empty() || (feats_undistort == NULL)) continue;

            flg_EKF_inited = (Measures.lidar_beg_time - first_lidar_time) < INIT_TIME ? false : true;
            lasermap_fov_segment();
            downSizeFilterSurf.setInputCloud(feats_undistort);
            downSizeFilterSurf.filter(*feats_down_body);
            feats_down_size = feats_down_body->points.size();
            if(ikdtree.Root_Node == nullptr)
            {
                if(feats_down_size > 5)
                {
                    ikdtree.set_downsample_param(filter_size_map_min);
                    feats_down_world->resize(feats_down_size);
                    for(int i = 0; i < feats_down_size; i++)
                        pointBodyToWorld(&(feats_down_body->points[i]), &(feats_down_world->points[i]));
                    ikdtree.Build(feats_down_world->points);
                }
                continue;
            }
            if (feats_down_size < 5) continue;
            normvec->resize(feats_down_size);
            feats_down_world->resize(feats_down_size);
            pointSearchInd_surf.resize(feats_down_size);
            Nearest_Points.resize(feats_down_size);

            double solve_H_time = 0;
            kf.update_iterated_dyn_share_modified(LASER_POINT_COV, solve_H_time);
            state_point = kf.get_x();
            pos_lid = state_point.pos + state_point.rot * state_point.offset_T_L_I;
            map_incremental();

            const double t5 = omp_get_wtime();
            const auto& q = state_point.rot;
            fpose << std::fixed << std::setprecision(6) << lidar_end_time << " " << std::setprecision(9)
                  << state_point.pos(0) << " " << state_point.pos(1) << " " << state_point.pos(2) << " "
                  << q.x() << " " << q.y() << " " << q.z() << " " << q.w() << "\n";
            fstat << std::fixed << std::setprecision(6) << lidar_end_time << "," << (t5 - t0) * 1e3 << ","
                  << feats_down_size << "," << effct_feat_num << "\n";
        }
    }
    fclose(lf);
    const double wall = std::chrono::duration<double>(std::chrono::steady_clock::now() - wall0).count();
    std::cout << "scans=" << n_scans << " wall_s=" << wall << " out=" << out_dir << std::endl;
    return 0;
}
